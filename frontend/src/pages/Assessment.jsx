import {
  Activity,
  AlertTriangle,
  CheckCircle2,
  CircleGauge,
  ShieldCheck,
} from 'lucide-react'

function Assessment({ result }) {
  // The result is returned by the Python /predict API.
  // Do not show made-up scores if the API has not returned a result.
  if (!result) {
    return (
      <div className="rounded-2xl border border-amber-200 bg-amber-50 p-6">
        <div className="flex items-start gap-3">
          <AlertTriangle className="mt-0.5 h-5 w-5 shrink-0 text-amber-600" />
          <div>
            <h2 className="font-semibold text-amber-900">
              Assessment result is not available
            </h2>
            <p className="mt-2 text-sm leading-6 text-amber-800">
              No prediction was received from the backend. Go back to the review
              screen and submit the assessment again.
            </p>
          </div>
        </div>
      </div>
    )
  }

  const creditScore = Number(result.creditScore)
  const maxScore = Number(result.maxScore) || 900
  const scorePercentage = Number.isFinite(creditScore)
    ? Math.min(100, Math.max(0, (creditScore / maxScore) * 100))
    : 0

  const defaultProbability = Number(result.defaultProbability)
  const probabilityText = Number.isFinite(defaultProbability)
    ? `${defaultProbability.toFixed(1)}%`
    : 'N/A'

  const riskCategory = result.riskCategory || 'Unclassified'
  const normalizedRisk = riskCategory.toLowerCase()
  const isLowRisk = normalizedRisk.includes('low')
  const isModerateRisk = normalizedRisk.includes('moderate')

  const riskStyles = isLowRisk
    ? {
        panel: 'bg-emerald-50',
        title: 'text-emerald-700',
        text: 'text-emerald-700',
        iconPanel: 'bg-emerald-100',
        icon: 'text-emerald-600',
      }
    : isModerateRisk
      ? {
          panel: 'bg-amber-50',
          title: 'text-amber-700',
          text: 'text-amber-700',
          iconPanel: 'bg-amber-100',
          icon: 'text-amber-600',
        }
      : {
          panel: 'bg-rose-50',
          title: 'text-rose-700',
          text: 'text-rose-700',
          iconPanel: 'bg-rose-100',
          icon: 'text-rose-600',
        }

  const positiveFactors = Array.isArray(result.positiveFactors)
    ? result.positiveFactors
    : []
  const riskFactors = Array.isArray(result.riskFactors)
    ? result.riskFactors
    : []

  const modelInfo = result.modelInfo || {}
  const disclaimer =
    result.disclaimer ||
    'Experimental demonstration only. This model has not been validated on NBCFDC beneficiary records and must not be used as an official lending decision.'

  return (
    <div>
      <div className="mb-8">
        <p className="text-sm font-semibold uppercase tracking-wide text-blue-600">
          Step 7 of 7
        </p>

        <h2 className="mt-2 text-3xl font-bold text-slate-900">
          Credit Risk Assessment
        </h2>

        <p className="mt-2 max-w-2xl text-slate-600">
          The prediction is generated by the connected Python ML model. Profile
          indicators below are based on the applicant's self-reported form
          responses.
        </p>
      </div>

      <div className="grid gap-6 lg:grid-cols-3">
        <div className="rounded-2xl border border-slate-200 bg-white p-8 shadow-sm lg:col-span-2">
          <div className="flex items-center gap-3">
            <div className="flex h-11 w-11 items-center justify-center rounded-xl bg-blue-100">
              <CircleGauge className="h-6 w-6 text-blue-600" />
            </div>

            <div>
              <p className="text-sm text-slate-500">Credit Assessment Score</p>
              <h3 className="text-lg font-semibold text-slate-900">
                Alternative Credit Score
              </h3>
            </div>
          </div>

          <div className="mt-8 flex flex-col items-center">
            <div className="relative flex h-52 w-52 items-center justify-center rounded-full border-[16px] border-blue-100">
              <div className="text-center">
                <p className="text-5xl font-bold text-slate-900">
                  {Number.isFinite(creditScore) ? creditScore : 'N/A'}
                </p>
                <p className="mt-1 text-sm text-slate-500">
                  out of {maxScore}
                </p>
              </div>
            </div>

            <div className="mt-6 w-full max-w-md">
              <div className="mb-2 flex justify-between text-xs text-slate-500">
                <span>Lower</span>
                <span>Higher</span>
              </div>

              <div className="h-3 overflow-hidden rounded-full bg-slate-200">
                <div
                  className="h-full rounded-full bg-blue-600 transition-all duration-500"
                  style={{ width: `${scorePercentage}%` }}
                />
              </div>
            </div>
          </div>

          <p className="mt-6 text-center text-xs leading-5 text-slate-500">
            Prototype score for demonstration only; it is not an official credit
            bureau score.
          </p>
        </div>

        <div className="rounded-2xl border border-slate-200 bg-white p-8 shadow-sm">
          <div className="flex items-center gap-3">
            <div
              className={`flex h-11 w-11 items-center justify-center rounded-xl ${riskStyles.iconPanel}`}
            >
              <ShieldCheck className={`h-6 w-6 ${riskStyles.icon}`} />
            </div>

            <div>
              <p className="text-sm text-slate-500">Risk Category</p>
              <h3 className="text-lg font-semibold text-slate-900">
                Model Assessment
              </h3>
            </div>
          </div>

          <div className={`mt-8 rounded-xl p-5 text-center ${riskStyles.panel}`}>
            <p className={`text-2xl font-bold ${riskStyles.title}`}>
              {riskCategory}
            </p>
            <p className={`mt-2 text-sm ${riskStyles.text}`}>
              Based on the model's estimated default probability
            </p>
          </div>

          <div className="mt-6 border-t border-slate-200 pt-6">
            <p className="text-sm text-slate-500">
              Estimated Default Probability
            </p>

            <div className="mt-2 flex items-end gap-2">
              <span className="text-3xl font-bold text-slate-900">
                {probabilityText}
              </span>
              <span className="pb-1 text-sm text-slate-500">model estimate</span>
            </div>
          </div>
        </div>
      </div>

      <div className="mt-6 rounded-2xl border border-slate-200 bg-white p-8 shadow-sm">
        <div className="flex items-center gap-3">
          <div className="flex h-11 w-11 items-center justify-center rounded-xl bg-emerald-100">
            <CheckCircle2 className="h-6 w-6 text-emerald-600" />
          </div>

          <div>
            <h3 className="text-lg font-semibold text-slate-900">
              Positive Profile Indicators
            </h3>
            <p className="text-sm text-slate-500">
              Positive signals identified from the form responses; these are not
              formal explanations of the ML model.
            </p>
          </div>
        </div>

        <div className="mt-6 grid gap-4 md:grid-cols-2">
          {positiveFactors.length > 0 ? (
            positiveFactors.map((factor, index) => (
              <div
                key={`${factor}-${index}`}
                className="flex items-start gap-3 rounded-xl bg-emerald-50 p-4"
              >
                <CheckCircle2 className="mt-0.5 h-5 w-5 shrink-0 text-emerald-600" />
                <p className="text-sm leading-6 text-emerald-900">{factor}</p>
              </div>
            ))
          ) : (
            <p className="text-sm text-slate-500">
              No positive profile indicators were returned.
            </p>
          )}
        </div>
      </div>

      <div className="mt-6 rounded-2xl border border-slate-200 bg-white p-8 shadow-sm">
        <div className="flex items-center gap-3">
          <div className="flex h-11 w-11 items-center justify-center rounded-xl bg-amber-100">
            <AlertTriangle className="h-6 w-6 text-amber-600" />
          </div>

          <div>
            <h3 className="text-lg font-semibold text-slate-900">
              Factors Requiring Attention
            </h3>
            <p className="text-sm text-slate-500">
              Potential concerns identified from the form responses.
            </p>
          </div>
        </div>

        <div className="mt-6 grid gap-4 md:grid-cols-2">
          {riskFactors.length > 0 ? (
            riskFactors.map((factor, index) => (
              <div
                key={`${factor}-${index}`}
                className="flex items-start gap-3 rounded-xl bg-amber-50 p-4"
              >
                <AlertTriangle className="mt-0.5 h-5 w-5 shrink-0 text-amber-600" />
                <p className="text-sm leading-6 text-amber-900">{factor}</p>
              </div>
            ))
          ) : (
            <p className="text-sm text-slate-500">
              No risk indicators were returned.
            </p>
          )}
        </div>
      </div>

      <div className="mt-6 rounded-2xl border border-blue-200 bg-blue-50 p-6">
        <div className="flex items-start gap-3">
          <Activity className="mt-0.5 h-5 w-5 shrink-0 text-blue-600" />

          <div>
            <h3 className="font-semibold text-blue-900">
              About This Assessment
            </h3>
            <p className="mt-2 text-sm leading-6 text-blue-800">
              {disclaimer}
            </p>

            {modelInfo.version && (
              <p className="mt-3 text-xs leading-5 text-blue-700">
                Model version: {modelInfo.version}
                {Number.isFinite(Number(modelInfo.testRocAuc)) &&
                  ` • Kaggle test ROC-AUC: ${Number(modelInfo.testRocAuc).toFixed(4)}`}
                {Number.isFinite(Number(modelInfo.testRecords)) &&
                  Number(modelInfo.testRecords) > 0 &&
                  ` • Held-out test records: ${Number(modelInfo.testRecords).toLocaleString()}`}
              </p>
            )}
          </div>
        </div>
      </div>
    </div>
  )
}

export default Assessment
